#!/usr/bin/env node
/* Build step: node app/build.js
   - app/inline-data.js : data/chips.json + data/models.json as a script (fallback for file:// where fetch() is blocked)
   - app/index.html     : modular page (src/*.css, src/*.js linked). Loads ../data/*.json via fetch on http(s), falls back to inline-data.js.
   - app/infrasim.html  : single self-contained file (CSS, JS and data inlined). Works from file://. */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), src = path.join(__dirname, 'src');
const read = p => fs.readFileSync(p, 'utf8');
const chips = JSON.parse(read(path.join(root, 'data/chips.json'))), models = JSON.parse(read(path.join(root, 'data/models.json')));
const safe = s => s.replace(/<\/(script)/gi, '<\\/$1').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
const tpl = read(path.join(src, 'template.html'));
const css = read(path.join(src, 'styles.css')), engine = read(path.join(src, 'engine.js')), ui = read(path.join(src, 'ui.js'));
const inlineJs = d => 'window.__INFRASIM_DATA__=' + safe(JSON.stringify(d)) + ';';
fs.writeFileSync(path.join(__dirname, 'inline-data.js'), '/* generated by build.js from data/*.json */\n' + inlineJs({ chips, models }) + '\n');
fs.writeFileSync(path.join(__dirname, 'index.html'), tpl
  .replace('<!--__CSS__-->', '<link rel="stylesheet" href="src/styles.css">')
  .replace('<!--__SCRIPTS__-->', '<script src="inline-data.js"></script>\n<script src="src/engine.js"></script>\n<script src="src/ui.js"></script>'));
fs.writeFileSync(path.join(__dirname, 'infrasim.html'), tpl
  .replace('<!--__CSS__-->', () => '<style>\n' + css + '</style>')
  .replace('<!--__SCRIPTS__-->', () => '<script>\n' + inlineJs({ chips, models, inlineOnly: true }) + '\n</script>\n<script>\n' + safe(engine) + '\n</script>\n<script>\n' + safe(ui) + '\n</script>'));
console.log('built: app/inline-data.js, app/index.html, app/infrasim.html (' + Math.round(fs.statSync(path.join(__dirname, 'infrasim.html')).size / 1024) + ' KB)');
